"""Project-built custom footprint factories — mechanical, connector, and
flex-antenna parts whose `.kicad_mod` lives in `library_kicad/footprints.pretty/`
(originally generated by `tools/lib-import/gen_lga_footprint.py` or
`gen_nfc_antenna.py`, then hand-tuned).

These are all `Chip` records with a Footprint but minimal datasheet
data — they describe physical interfaces on the Smash board, not real
silicon parts.
"""

from __future__ import annotations

import functools
import math

from smash.state import Chip, Pin, Footprint
from smash.parts._artifacts import (
    pads_from_kicad_mod, outline_polygon, src, datasheet_ref,
)


def _project_footprint(part_dir: str, fp_name: str, *,
                       package_class: str, height_mm: float | None = None,
                       size_mm: tuple | None = None,
                       pitch_mm: float | None = None,
                       note: str = "") -> Footprint:
    """Common builder for project-built footprints. Pads + outline +
    courtyard parsed directly from the `.kicad_mod`.

    `.kicad_mod` F.CrtYd polygons sometimes hug the pads (or are absent),
    so the courtyard is normalised to clear the lands by >= the standard
    ring — the packer abuts courtyards, and a tight one shorts a dense
    field (e.g. the 45-up pogo bench)."""
    fp_mod = src(part_dir, f"{fp_name}.kicad_mod")
    return Footprint(
        name=fp_name,
        package_class=package_class,
        pads=pads_from_kicad_mod(fp_mod),
        body_outline=outline_polygon(fp_mod, "F.Fab"),
        courtyard=outline_polygon(fp_mod, "F.CrtYd"),
        pitch_mm=pitch_mm,
        size_mm=size_mm,
        height_mm=height_mm,
        model_3d_path=None,
        source="project (library_kicad/footprints.pretty/)",
        note=note,
    ).ensure_courtyard_clearance()


def _pins_from_pads(footprint: Footprint, name_map: dict | None = None) -> list:
    """Default Pin list: one Pin per UNIQUE pad num. A KiCad footprint
    can have multiple Pad entries sharing the same num (e.g. a stitched
    thermal pad, or a multi-via net jumper) — those collapse to a
    single Pin in the design's electrical model.

    If `name_map` is given, it overrides the pin name per pad-num;
    otherwise pin name == pad num.
    """
    name_map = name_map or {}
    seen: set = set()
    pins = []
    for pad in footprint.pads:
        if pad.num in seen:
            continue
        seen.add(pad.num)
        pins.append(Pin(
            num=pad.num,
            name=name_map.get(pad.num, pad.num),
        ))
    return pins


