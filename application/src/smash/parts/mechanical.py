# NFC_Antenna_Flex_27x50 — flex-only 4-turn etched spiral antenna
# ═════════════════════════════════════════════════════════════════════════

def _nfc_spiral_points(
    width_mm: float, length_mm: float, turns: int,
    trace_mm: float, gap_mm: float,
    edge_clearance_mm: float = 0.5,
    start_xy: tuple | None = None,
    terminate_y: float | None = None,
) -> tuple:
    """Generate the rectangular-spiral polyline plus inner-end position.

    Returns `(points, inner_end_xy)`. The spiral winds CW from the
    outer top-left corner. `inner_end_xy` is the innermost terminus
    where the AC1 bridge picks up (a via to B.Cu).

    If `start_xy` is supplied, the polyline is prefixed with a two-
    segment lead-in (east to the spiral's outer west edge, then north
    to the top-left corner) so the trace visibly originates at the
    AC0 feed pad.

    If `terminate_y` is supplied (typically the y-coord of the AC1
    pad), the final turn keeps descending the inner west edge to that
    y so the B.Cu bridge from AC1 lands a short horizontal stub away
    from the inner spiral. Without it, the final segment stops half
    a pitch below the inner top corner.

    Nesting is done by climbing the west edge stopping `pitch` short
    of the top, then stepping right by `pitch` into the next inner
    top-left corner. Skipping that climb (jumping diagonally between
    turns) produces a visible "shortcut" in the corner — see
    https://github.com/.../issue if it reappears.
    """
    pitch = trace_mm + gap_mm
    inset = edge_clearance_mm + trace_mm / 2
    x_max = width_mm / 2 - inset
    y_max = length_mm / 2 - inset
    x_min, y_min = -x_max, -y_max

    pts: list[tuple] = []
    if start_xy is not None:
        sx, sy = start_xy
        pts.append(start_xy)
        # Lead-in stays OUTSIDE the spiral's outer west edge: go
        # straight up the pad's own column to the spiral's top y, then
        # a short east stub joins the outer top-left corner. Routing
        # via (x_min, sy) instead would lay the lead-in on top of the
        # spiral's first-turn west edge — a visible overlap from
        # y=sy up to (y_max - pitch).
        pts.append((sx, y_max))

    pts.append((x_min, y_max))   # outer top-left corner
    for turn in range(turns):
        pts.append((x_max, y_max))    # top edge, west → east
        pts.append((x_max, y_min))    # east edge, north → south
        pts.append((x_min, y_min))    # bottom edge, east → west
        if turn < turns - 1:
            # West edge, climbing back up but stopping pitch short of
            # the start so the next turn can nest cleanly inside.
            pts.append((x_min, y_max - pitch))
            # Step right by pitch — this lands exactly at the next
            # turn's top-left corner.
            x_max -= pitch; y_max -= pitch
            x_min += pitch; y_min += pitch
            pts.append((x_min, y_max))
        else:
            # Innermost turn. Either descend to the user-specified
            # terminate_y (aligns with the AC1 pad) or fall back to a
            # short half-pitch stub.
            if terminate_y is not None:
                pts.append((x_min, terminate_y))
            else:
                pts.append((x_min, y_max - pitch / 2))

    inner_end = pts[-1]
    return pts, inner_end


_NFC_W, _NFC_H = 20.0, 35.0
_NFC_TURNS, _NFC_TRACE, _NFC_GAP = 8, 0.3, 0.3

# Round coil (operates like the camera tile so it S-folds): Ø22 disc,
# 0.2/0.2 mm trace/gap, 17 turns → L ≈ 4.82 µH, which resonates at
# 13.56 MHz against the ST25DV16KC's fixed internal Ctun = 28.5 pF (no
# external trim cap). Solved with the Mohan current-sheet model; see
# memory ref_st25dv_antenna_L.
_NFC_DIA = 22.0
_NFC_TURNS_R, _NFC_TRACE_R, _NFC_GAP_R = 17, 0.2, 0.2
_NFC_EDGE_CLEAR_R = 0.5


def _nfc_round_spiral_points(diameter_mm: float, turns: int,
                             trace_mm: float, gap_mm: float,
                             edge_clearance_mm: float = 0.5,
                             start_angle_deg: float = 90.0,
                             seg_per_turn: int = 48,
                             start_xy: tuple | None = None) -> tuple:
    """Archimedean circular spiral `r(θ) = r_out − (pitch/2π)·θ` as a
    segmented polyline winding inward from the outer edge. Returns
    `(points, inner_end_xy)`. `start_angle_deg` sets the outer terminus
    (90° = North) so the feed pads sit just outboard of it; `start_xy`
    prepends a short radial lead-in from the AC0 pad."""
    pitch = trace_mm + gap_mm
    r_out = diameter_mm / 2.0 - edge_clearance_mm - trace_mm / 2.0
    a0 = math.radians(start_angle_deg)
    pts: list[tuple] = []
    if start_xy is not None:
        pts.append(start_xy)
    steps = max(1, int(seg_per_turn * turns))
    for i in range(steps + 1):
        frac = i / steps
        theta = a0 + 2.0 * math.pi * turns * frac     # wind inward (CCW)
        r = r_out - pitch * turns * frac
        pts.append((r * math.cos(theta), r * math.sin(theta)))
    return pts, pts[-1]


def _reflect(geom, *, fx=1.0, fy=1.0):
    p1, p2, spiral, inner = geom
    f = lambda xy: (fx * xy[0], fy * xy[1])
    return f(p1), f(p2), tuple(f(p) for p in spiral), f(inner)


@functools.lru_cache(maxsize=None)
def _nfc_geometry(feed_edge: str):
    """Pad + spiral geometry for the antenna whose feed sits on
    `feed_edge` (the flex-entry side). Cached — the coil is deterministic
    per edge, so the generated "NFC tag" for each orientation is computed
    once and reused.

    Round Ø22 coil (see `_nfc_round_spiral_points`). `north` is canonical
    — the two feed pads sit just outboard of the spiral's North outer
    terminus; AC0 feeds the outer end, AC1 bridges to the inner terminus
    on B.Cu. Other edges rotate the start angle. Returns
    `(pad1_xy, pad2_xy, spiral_pts, spiral_inner_xy)`."""
    r_out = _NFC_DIA / 2.0 - _NFC_EDGE_CLEAR_R - _NFC_TRACE_R / 2.0
    start_angle = {"north": 90.0, "south": -90.0,
                   "east": 0.0, "west": 180.0}.get(feed_edge)
    if start_angle is None:
        raise ValueError(f"unknown NFC feed_edge {feed_edge!r} "
                         "(expected north/south/east/west)")
    # Outer terminus + the two feed pads just outboard of it, offset
    # tangentially so AC0/AC1 sit side by side off the disc edge.
    a = math.radians(start_angle)
    ux, uy = math.cos(a), math.sin(a)          # radial (outward)
    tx, ty = -uy, ux                           # tangential
    # Pads sit in the gap between the outer turn (r_out) and the disc rim,
    # so they stay on-board and clear of the inner turns.
    r_pad = (r_out + _NFC_DIA / 2.0) / 2.0
    p1 = (r_pad * ux - 0.5 * tx, r_pad * uy - 0.5 * ty)   # AC0 feed
    p2 = (r_pad * ux + 0.5 * tx, r_pad * uy + 0.5 * ty)   # AC1 bridge
    spiral, inner = _nfc_round_spiral_points(
        _NFC_DIA, _NFC_TURNS_R, _NFC_TRACE_R, _NFC_GAP_R,
        edge_clearance_mm=_NFC_EDGE_CLEAR_R,
        start_angle_deg=start_angle, start_xy=p1)
    return p1, p2, tuple(spiral), inner


def add_nfc_antenna_flex_27x50(design, ref: str = "L_NFC_ANT",
                               feed_edge: str = "north",
                               **overrides) -> Chip:
    """Flex-only 17-turn ROUND spiral antenna for NFC, Ø22 mm.

    `feed_edge` selects which disc edge the two AC0/AC1 feed pads sit on
    — the edge the rigid-flex strip launches from. The per-edge geometry
    is cached (`_nfc_geometry`).

    Sized to L ≈ 4.82 µH (Mohan current-sheet, Ø22 / 0.2 mm trace / 0.2 mm
    gap / 17 turns), which resonates at 13.56 MHz against the ST25DV16KC's
    FIXED internal Ctun = 28.5 pF — no external trim cap (the chip has no
    trim pin). Memory ref_st25dv_antenna_L.

    The round form (vs the old 20×35 rect) lets the NFC tile behave like
    the camera/qpd tiles — a small Ø22 disc that S-folds off the snake
    flex instead of claiming a full grid cell.

    Two electrical pins (AC0/AC1). The .kicad_mod from gen_nfc_antenna.py
    was generated for the old 27×50 rect footprint — body_outline,
    courtyard and copper are overridden here to the round coil.
    """
    part = "NFC_Antenna_Flex_27x50"   # KiCad lib id kept for net-list compat
    fp = _project_footprint(
        part, "NFC_Antenna_Flex_27x50",
        package_class="NFC spiral antenna (flex copper)",
        size_mm=(_NFC_DIA, _NFC_DIA),
        note=(
            "17-turn round spiral, Ø22 mm, 0.2 mm trace + 0.2 mm gap. "
            "Two SMD feed pads just outboard of the coil (flex-entry "
            "side). L ≈ 4.82 µH, resonates at 13.56 MHz against the "
            "ST25DV16KC's fixed 28.5 pF internal Ctun (no trim cap)."
        ),
    )
    # The .kicad_mod's body_outline + courtyard target the old 27×50
    # rect; override with the round Ø22 disc.
    R = _NFC_DIA / 2.0
    crt = 0.25       # IPC-7351 standard courtyard clearance
    circ = [(R * math.cos(t), R * math.sin(t))
            for t in (math.radians(d) for d in range(0, 360, 10))]
    fp.body_outline = circ
    fp.courtyard = [((R + crt) * math.cos(t), (R + crt) * math.sin(t))
                    for t in (math.radians(d) for d in range(0, 360, 10))]
    # Feed pads + spiral for the requested flex-entry edge (cached).
    pad1_pos, pad2_pos, spiral_pts, spiral_inner = _nfc_geometry(feed_edge)
    spiral_pts = list(spiral_pts)          # detach from the cached tuple
    fp.copper_lines.append({
        "layer":    "F.Cu",
        "width_mm": _NFC_TRACE_R,
        "points":   spiral_pts,
    })

    for p in fp.pads:
        # SMD feed pads move to the north edge (flex-launch side).
        if p.num == "1" and p.shape == "rect":
            p.position_mm = pad1_pos
        elif p.num == "2" and p.shape == "rect":
            p.position_mm = pad2_pos
        # Two PTH bridge vias come from the .kicad_mod's old 27×50
        # geometry. Re-target them: one moves to the AC1 SMD pad (so
        # the F.Cu pad → B.Cu via is colocated); the other follows the
        # spiral to its new inner-end location.
        elif p.num == "2" and p.shape == "circle":
            old_x = p.position_mm[0]
            # In the source mod, the SMD-colocated via is at x=12.25
            # and the inner-end via is at x=11.05. Use position to
            # tell them apart.
            if abs(old_x - 12.25) < 0.5:
                p.position_mm = pad2_pos
            else:
                p.position_mm = spiral_inner

    # B.Cu bridge: AC1 pad's via → spiral inner-end via. The via at
    # `spiral_inner` brings the signal back up to F.Cu where the
    # spiral terminates internally.
    fp.copper_lines.append({
        "layer":    "B.Cu",
        "width_mm": _NFC_TRACE_R,
        "points":   [pad2_pos, spiral_inner],
    })
    fields = dict(
        manf="project", manf_pn=part, name=part,
        description=(
            "Flex spiral antenna for NFC (13.56 MHz), Ø22 mm, "
            "17-turn round, ~4.82 µH typical inductance"
        ),
        datasheet=None,
        package="Custom flex spiral",
        # Inductance drives ST25DV16KC resonance (fixed 28.5 pF Ctun).
        inductance_h=4.82e-6,
        pins=_pins_from_pads(fp, name_map={"1": "AC0", "2": "AC1"}),
        footprint=fp,
        note=(
            "Generated by `tools/lib-import/gen_nfc_antenna.py`, reshaped "
            "to a round Ø22 coil. Resonates at 13.56 MHz against "
            "ST25DV16KC's AC0/AC1 with its FIXED internal 28.5 pF Ctun — "
            "no external trim cap. Sits on the cylinder wall behind a "
            "housing window at the NFC location (no Al eddy currents)."
        ),
    )
    fields.update(overrides)
    return design.add_chip(ref=ref, **fields)


